console.log('pax/price value', await page.getByRole('spinbutton', { name: 'Pax Min' }).inputValue(), await page.getByRole('spinbutton', { name: 'Pax Max' }).inputValue(), await page.getByRole('spinbutton', { name: 'Base Price' }).inputValue());
