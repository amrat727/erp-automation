// Helper (not a test): READ-ONLY - lists the Role options of the "Add contact" dialog.  Run: node scripts/probe-contact-roles.mjs [supplierId]
import { chromium } from '@playwright/test';
import fs from 'fs';
const ID = process.argv[2] ?? '21';
const session = fs.readFileSync('playwright/.auth/session.json', 'utf-8');
const browser = await chromium.launch();
const ctx = await browser.newContext({ baseURL: process.env.BASE_URL ?? 'https://erp.nexgenpilot.com', viewport: { width: 1500, height: 950 } });
await ctx.addInitScript(d => { if (!sessionStorage.getItem('token')) for (const [k, v] of Object.entries(JSON.parse(d))) sessionStorage.setItem(k, v); }, session);
await ctx.route('**/pilottest.runasp.net/**', r => (['POST', 'PUT', 'DELETE', 'PATCH'].includes(r.request().method()) && !r.request().url().includes('negotiate')) ? r.abort() : r.continue());
const page = await ctx.newPage();
await page.goto(`/suppliers/${ID}/contacts`);
await page.getByRole('button', { name: /Add contact$/ }).last().waitFor({ timeout: 90_000 });
await page.waitForTimeout(3000);
await page.getByRole('button', { name: /Add contact$/ }).last().click();
const d = page.getByRole('dialog').last();
await d.getByPlaceholder('Reservations, Sales, Accounts…').click();
await page.waitForTimeout(2500);
console.log('ROLES:', JSON.stringify(await page.getByRole('option').allInnerTexts()));
console.log('PRIMARY NOTE:', JSON.stringify(await d.innerText()));
await browser.close();
